import Foundation

/// Bounds and privacy rules applied before clipboard data is read or persisted.
///
/// The pasteboard APIs do not expose a trustworthy source application for every
/// write. The monitor therefore requires the applications observed on both
/// sides of a change to be known and allowed, and fails closed when the
/// pasteboard marks data as transient or concealed.
enum ClipboardPolicy {
    static let maxTextBytes = 1 * 1024 * 1024
    static let maxURLBytes = 64 * 1024
    static let maxFilePathBytes = 64 * 1024
    static let maxRTFBytes = 2 * 1024 * 1024
    static let maxImageBytes = 10 * 1024 * 1024
    static let maxScreenshotSourceBytes = 128 * 1024 * 1024
    static let maxHistoryBytes = 25 * 1024 * 1024

    private static let maxImageBase64Bytes = ((maxImageBytes + 2) / 3) * 4
    private static let maxRTFBase64Bytes = ((maxRTFBytes + 2) / 3) * 4

    /// Pasteboard annotations used by password managers and other sensitive
    /// producers. These items must never be copied into persistent history.
    static let suppressedPasteboardTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType"
    ]

    static func containsSuppressedPasteboardType(_ typeIdentifiers: [String]) -> Bool {
        !suppressedPasteboardTypes.isDisjoint(with: typeIdentifiers)
    }

    /// The pasteboard does not expose a reliable producer application. The
    /// previous and current frontmost apps bracket the copy event between two
    /// polls. A transition is safe to retain only when both are known and both
    /// are outside the user's exclusion list. This preserves fast copy-then-
    /// switch workflows without ever bridging content across an excluded app.
    static func canStoreClipboardChange(
        previousBundleID: String?,
        currentBundleID: String?,
        excludedBundleIDs: Set<String>
    ) -> Bool {
        guard let previousBundleID,
              let currentBundleID else {
            return false
        }

        return !excludedBundleIDs.contains(previousBundleID)
            && !excludedBundleIDs.contains(currentBundleID)
    }

    static func acceptsStoredItem(
        content: String,
        contentType: ContentType,
        rtfContent: String?,
        filename: String? = nil
    ) -> Bool {
        let contentByteCount = content.lengthOfBytes(using: .utf8)

        switch contentType {
        case .text:
            guard contentByteCount <= maxTextBytes else { return false }
        case .url:
            guard contentByteCount <= maxURLBytes else { return false }
        case .file:
            guard contentByteCount <= maxFilePathBytes else { return false }
        case .image:
            guard contentByteCount <= maxImageBase64Bytes,
                  let imageData = Data(base64Encoded: content),
                  imageData.count <= maxImageBytes else {
                return false
            }
        }

        if let rtfContent {
            guard rtfContent.utf8.count <= maxRTFBase64Bytes,
                  let rtfData = Data(base64Encoded: rtfContent),
                  rtfData.count <= maxRTFBytes else {
                return false
            }
        }

        if let filename {
            guard filename.lengthOfBytes(using: .utf8) <= maxFilePathBytes else {
                return false
            }
        }

        return true
    }

    static func acceptsImagePasteboardData(byteCount: Int) -> Bool {
        byteCount >= 0 && byteCount <= maxImageBytes
    }

    static func acceptsRTFPasteboardData(byteCount: Int) -> Bool {
        byteCount >= 0 && byteCount <= maxRTFBytes
    }
}
